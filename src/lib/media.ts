import { API_BASE_URL } from "@/lib/api";

/**
 * Single, shared resolver for every product/store image URL coming
 * back from the backend.
 *
 * The backend already returns fully-absolute URLs in the normal case
 * -- see apps/products/infrastructure/selectors.py::_resolve_media_url,
 * which builds `${PUBLIC_BASE_URL}${MEDIA_URL}${storage_path}` server
 * side (and passes an already-absolute URL through unchanged). This
 * function is the frontend-side defensive counterpart for the one
 * documented edge case: PUBLIC_BASE_URL unset in the backend's own
 * environment leaves a root-relative path (e.g. "/media/products/x.jpg")
 * that would otherwise resolve against the Next.js origin instead of
 * the Django host that actually serves it. Never invents a URL, a
 * host, or a field -- it only joins a relative path against the same
 * NEXT_PUBLIC_API_BASE_URL this client already uses for every API
 * call (see lib/api.ts), and returns null for anything empty/absent
 * so callers can render their own neutral fallback instead of a
 * broken <img>.
 */
/**
 * Store/Banner/Brand/Category/Product detail hero images all come
 * back from the backend pinned to a single, fixed thumbnail size --
 * e.g. `apps/stores/interfaces/api/v1/views.py::_media_url`'s own
 * `size: str = "medium"` default, used for `cover_image_url` on both
 * the store list AND the store detail response alike. There is no
 * size parameter the frontend can request instead. Confirmed directly
 * (real store row inspected): the SAME upload always produces
 * `large`/`medium`/`small` siblings side by side -- `core.media.MediaPipeline`
 * always writes all three, never just one -- so the larger file
 * already exists on disk right now, the API just never links to it.
 *
 * This derives that sibling's URL from the one the API *did* give us,
 * for hero-sized placements only -- never invents a path, never
 * assumes a file exists beyond this one, always-true pipeline
 * guarantee. The caller MUST still handle a load failure (via
 * MediaImage's `onLoadError`) and fall back to the original medium
 * URL, in case this specific asset predates the 3-size pipeline.
 */
export function deriveLargeVariant(url: string | null | undefined): string | null {
  if (!url) return null;
  if (!url.endsWith(".medium.webp")) return null;
  return `${url.slice(0, -".medium.webp".length)}.large.webp`;
}

/**
 * The real, confirmed root cause of "product images load very slowly"
 * everywhere on this site (cards, search, recommendations, AND the
 * product detail gallery itself): `ProductMedia.storage_path` -- what
 * `primary_image_path`/`gallery[]` are always built from
 * (`apps/products/infrastructure/selectors.py::_resolve_media_url`) --
 * is the plain, full-resolution ORIGINAL upload, any real extension
 * (.jpg/.jpeg/.png/.webp). Confirmed directly against real
 * `ProductMedia` rows: the SAME row's own `thumbnail_paths`
 * (small/medium/large, always WebP, same content-hash prefix) already
 * exists on disk, generated by the identical MediaPipeline every other
 * module (Store/Brand/Category) already relies on -- the product
 * selector just never links to it, unlike those other modules.
 *
 * This is the purely mechanical, string-only derivation that requests
 * the RIGHT size instead, with zero backend change: swap the
 * original's own trailing extension for "<size>.webp", keeping the
 * same content-hash path in front of it.
 *
 * Returns null if `url` doesn't look like a file path at all. The
 * caller MUST still handle a load failure (via MediaImage's own
 * `onLoadError`) and fall back to the original `url` -- confirmed a
 * real, if uncommon, case: some seeded/fixture `ProductMedia` rows
 * have `thumbnail_paths: {}` (predate, or bypassed, the pipeline).
 */
export function deriveProductThumbnail(url: string | null | undefined, size: "small" | "medium" | "large"): string | null {
  if (!url) return null;
  // Already a derived thumbnail (defensive -- never double-derive off a sibling).
  const alreadyThumb = url.match(/^(.*)\.(?:small|medium|large)\.webp$/i);
  if (alreadyThumb) return `${alreadyThumb[1]}.${size}.webp`;
  const match = url.match(/^(.*)\.[a-zA-Z0-9]+$/);
  if (!match) return null;
  return `${match[1]}.${size}.webp`;
}

export function resolveImageUrl(url: string | null | undefined): string | null {
  if (!url) return null;
  const trimmed = url.trim();
  if (!trimmed) return null;
  if (trimmed.startsWith("data:")) return trimmed;

  try {
    if (/^(https?:)?\/\//i.test(trimmed)) {
      // Real, recurring bug (confirmed live, not hypothetical): every
      // real media URL this backend returns is fully-absolute, baked
      // with whichever PUBLIC_BASE_URL was active the moment that
      // specific response was generated -- see apps/products/
      // infrastructure/selectors.py::_resolve_media_url and its
      // equivalents. In this dev environment the backend's own public
      // host is a Cloudflare Quick Tunnel that gets a brand-new random
      // hostname every time it restarts; a chat attachment (or any
      // other image) sent under a previous hostname then pointed at a
      // permanently dead host forever after, even though the exact
      // same file (same storage path) is still served fine by *today's*
      // backend. Re-hosting onto the CURRENT API_BASE_URL -- keeping
      // only the real path -- is what makes a previously-sent image
      // keep working across a backend host rotation instead of going
      // permanently broken. Every real image field here is confirmed
      // self-hosted by this same backend (never a third-party URL), so
      // this is always correct, never a wrong rewrite of someone else's
      // domain.
      const absolute = trimmed.startsWith("//") ? `https:${trimmed}` : trimmed;
      const parsed = new URL(absolute);
      return `${API_BASE_URL}${parsed.pathname}${parsed.search}`;
    }
    // Root-relative ("/media/...") or bare relative path -- join
    // against the known API origin, never against window.location.
    const path = trimmed.startsWith("/") ? trimmed : `/${trimmed}`;
    return `${API_BASE_URL}${path}`;
  } catch {
    return null;
  }
}
