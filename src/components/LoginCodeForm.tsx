"use client";

import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { Loader2, Send, Timer } from "lucide-react";
import { useTranslations } from "next-intl";
import { mapAuthErrorCode } from "@/lib/auth-errors";
import { safeRedirectPath } from "@/lib/safe-redirect";
import OtpInput, { OTP_LENGTH } from "@/components/OtpInput";
import AuthLoadingScreen, { type AuthLoadingPhase } from "@/components/AuthLoadingScreen";

// Purely cosmetic: how long the success state stays on screen before
// navigating away, once the backend has already confirmed a real
// success. Never gates or delays the actual authentication request.
const SUCCESS_TRANSITION_MS = 450;

// Real, explicit product requirement: a login code is valid for
// exactly 2 minutes, matching the backend's own authoritative
// OTP_EXPIRY_SECONDS (apps/identity/domain/services.py::OTPPolicy)
// and the reference login experience this flow was rebuilt against
// ("Kod 2 daqiqada amal qiladi"). This is a client-side UX countdown
// only -- the backend's own expires_at check on the challenge row is
// what actually enforces this, so a client clock a few seconds off
// never lets an expired code through or blocks a valid one for long.
const CODE_VALIDITY_SECONDS = 120;

// The bot's real, deployed @username -- must match the backend's own
// TELEGRAM_BOT_USERNAME setting exactly (Django system check
// telegram_bot.E002 fails loudly at deploy time if that's ever
// unset). Never hardcoded: a stale hardcoded username here would
// silently deep-link customers to the wrong bot, or to a bot that no
// longer exists, the moment either value changes.
const TELEGRAM_BOT_USERNAME = process.env.NEXT_PUBLIC_TELEGRAM_BOT_USERNAME;

function formatCountdown(totalSeconds: number): string {
  const m = Math.floor(totalSeconds / 60);
  const s = totalSeconds % 60;
  return `${m}:${s.toString().padStart(2, "0")}`;
}

/**
 * Real, product-required rebuild: the website's login page never
 * collects a phone number at all, and no longer offers a separate
 * session-polling "auto-login" button either -- one button is the
 * entire entry point: it opens the Telegram bot, the user taps "Get
 * login code" there, and types the resulting 6-digit code here. Calls
 * the existing, dedicated /api/auth/verify-code endpoint (no
 * phone_number field exists on this form or in its request body).
 */
export default function LoginCodeForm({ redirectTo }: { redirectTo: string }) {
  const router = useRouter();
  const t = useTranslations("auth.loginCode");
  const tTelegram = useTranslations("auth.telegram");
  const tAuth = useTranslations("auth");
  const tAuthLoading = useTranslations("authLoading");
  const tPage = useTranslations("auth.loginPage");

  const [code, setCode] = useState("");
  const [loading, setLoading] = useState(false);
  const [errorKey, setErrorKey] = useState<string | null>(null);
  // null until the customer opens the bot from here: a code they fetched some other way (bot already open on
  // their phone) must never be blocked by a timer that started when this page loaded. The backend enforces expiry.
  const [secondsLeft, setSecondsLeft] = useState<number | null>(null);
  const [authPhase, setAuthPhase] = useState<AuthLoadingPhase | null>(null);
  // Synchronous guard against a duplicate verify-code request: `loading`
  // state alone is not enough -- it only takes effect once React commits
  // the next render, so two clicks/taps that both land before that
  // commit (a real, common double-tap on mobile) can both read
  // `loading === false` and both fire a request. A ref updates
  // immediately, in the same tick as the first call, so the second
  // invocation -- however soon it arrives -- always sees it set.
  const submittingRef = useRef(false);

  const counting = secondsLeft !== null && secondsLeft > 0;
  const expired = secondsLeft === 0;

  useEffect(() => {
    if (!counting) return;
    const id = setInterval(() => setSecondsLeft((s) => (s === null ? null : Math.max(0, s - 1))), 1000);
    return () => clearInterval(id);
  }, [counting]);

  function handleOpenBot() {
    // Real, product-required simplification: this is now the page's
    // one and only entry point (no separate session-polling
    // "auto-login" button), so it deep-links straight to the bot's
    // real "?start=login" payload -- the backend's own _handle_start
    // (apps/telegram_bot/interfaces/api/v1/views.py) treats this
    // identically to a bare /start: it opens the customer's chat with
    // the bot and, for an already-registered customer, shows the main
    // menu, nothing more. The code is only ever generated by the
    // customer explicitly pressing "Sayt uchun kod olish" themselves
    // inside that chat, never automatically by this link. The 2-minute countdown
    // below is restarted here too, since pressing this button is the
    // real, product-visible "I'm about to go get a fresh code" moment
    // -- a far better anchor for the countdown than whenever this page
    // happened to load.
    if (!TELEGRAM_BOT_USERNAME) return;
    window.open(`https://t.me/${TELEGRAM_BOT_USERNAME}?start=login`, "_blank", "noopener,noreferrer");
    setCode("");
    setErrorKey(null);
    setSecondsLeft(CODE_VALIDITY_SECONDS);
  }

  async function handleLogin(value = code) {
    if (value.length !== OTP_LENGTH || loading || submittingRef.current) return;
    submittingRef.current = true;
    setErrorKey(null);
    setLoading(true);
    setAuthPhase("loading");
    try {
      const res = await fetch("/api/auth/verify-code", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        // Defense in depth: OtpInput now guarantees a clean 6-digit
        // string, but a non-digit character here would previously
        // have failed the backend's OTPCode validation with an
        // opaque error -- stripped here too so the only way this can
        // ever fail is a genuinely wrong or expired code.
        body: JSON.stringify({ code: value.replace(/\D/g, "") }),
      });
      const body = await res.json();
      if (!res.ok || !body.success) {
        setErrorKey(mapAuthErrorCode(body.error?.code ?? "UNKNOWN"));
        setCode("");
        setAuthPhase("error");
        return;
      }
      // Real success already confirmed above -- this only delays the
      // redirect for a short, purely cosmetic beat (never the other
      // way around: the animation never decides when auth is "done").
      setAuthPhase("success");
      await new Promise((resolve) => setTimeout(resolve, SUCCESS_TRANSITION_MS));
      router.push(safeRedirectPath(redirectTo));
      router.refresh();
    } catch {
      setErrorKey("network");
      setAuthPhase("error");
    } finally {
      setLoading(false);
      submittingRef.current = false;
    }
  }

  function handleRetry() {
    setAuthPhase(null);
  }

  return (
    <div>
      {authPhase && (
        <AuthLoadingScreen
          phase={authPhase}
          title={authPhase === "success" ? tAuthLoading("welcomeBack") : authPhase === "error" ? tAuthLoading("errorTitle") : tAuthLoading("signingIn")}
          subtitle={
            authPhase === "success"
              ? tAuthLoading("preparing")
              : authPhase === "error"
                ? errorKey === "network"
                  ? tAuth("networkError")
                  : tAuth(`errors.${errorKey ?? "unknown"}` as "errors.unknown")
                : tAuthLoading("verifyingCode")
          }
          onRetry={handleRetry}
          retryLabel={tAuthLoading("tryAgain")}
        />
      )}

      {/* how it works */}
      <ol className="mb-5 space-y-2">
        {(["step1", "step2", "step3"] as const).map((key, i) => (
          <li key={key} className="flex items-center gap-3 text-[13px] text-ink-muted">
            <span className={`flex h-6 w-6 shrink-0 items-center justify-center rounded-full text-[11px] font-bold ${i === 2 && code.length > 0 ? "bg-primary text-primary-contrast" : "bg-primary-soft text-primary"}`}>{i + 1}</span>
            {tPage(key)}
          </li>
        ))}
      </ol>

      {TELEGRAM_BOT_USERNAME && (
        <button
          type="button"
          onClick={handleOpenBot}
          className="nz-telegram-btn nz-shimmer-btn group flex w-full items-center justify-center gap-2.5 rounded-2xl px-6 py-4 text-base font-bold text-white"
        >
          <Send className="h-5 w-5 transition-transform group-hover:-translate-y-0.5 group-hover:translate-x-0.5" strokeWidth={2} aria-hidden="true" />
          {tTelegram("continueWith")}
        </button>
      )}

      <div className="my-6 flex items-center gap-3" role="separator">
        <div className="h-px flex-1 bg-gradient-to-r from-transparent to-border" />
        <span className="text-[11px] font-semibold uppercase tracking-[0.18em] text-ink-soft">{t("title")}</span>
        <div className="h-px flex-1 bg-gradient-to-l from-transparent to-border" />
      </div>

      <OtpInput
        variant="premium"
        value={code}
        disabled={loading}
        invalid={!!errorKey}
        onChange={(v) => {
          setCode(v);
          if (errorKey) setErrorKey(null);
          if (v.length === OTP_LENGTH) handleLogin(v);
        }}
      />

      <p className={`mt-4 flex items-center justify-center gap-1.5 text-center text-xs font-medium tabular-nums ${expired ? "text-amber-400" : "text-ink-muted"}`} aria-live="polite">
        <Timer className="h-3.5 w-3.5" strokeWidth={2} aria-hidden="true" />
        {expired ? t("codeExpired") : counting ? t("validFor", { time: formatCountdown(secondsLeft ?? 0) }) : tPage("codeHint")}
      </p>

      {errorKey && (
        <p role="alert" aria-live="polite" className="mt-3 rounded-xl border border-red-500/30 bg-red-500/10 px-3 py-2 text-center text-sm text-red-300">
          {errorKey === "network" ? tAuth("networkError") : tAuth(`errors.${errorKey}` as "errors.unknown")}
        </p>
      )}

      <button type="button" onClick={() => handleLogin()} disabled={loading || code.length !== OTP_LENGTH} className="nz-cta mt-5 flex w-full items-center justify-center gap-2 rounded-xl px-6 py-3.5 text-sm font-bold disabled:opacity-50">
        {loading && <Loader2 className="h-4 w-4 animate-spin" strokeWidth={2} aria-hidden="true" />}
        {loading ? t("loggingIn") : t("loginButton")}
      </button>
      <p className="mt-2 text-center text-[11px] text-ink-soft">{tPage("autoHint")}</p>

      {expired && TELEGRAM_BOT_USERNAME && (
        <button type="button" onClick={handleOpenBot} className="mt-3 block w-full text-center text-sm font-semibold text-primary hover:underline">
          {tPage("newCode")}
        </button>
      )}
    </div>
  );
}
